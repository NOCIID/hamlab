"""
A SplitJEPA-style diagnostic (hamlab/solvers/gpdp/memory_split.py): is the learned memory's failure a
mixing of "when" with "how high are prices", and does keeping only the invariant part of h help?

For each seed, the GPDP run memlearn_v4_zkh_s<seed> (alpha = 1, policy GP on (z, K, h), learned GRU) is replayed (training is
deterministic: the replay's final rule is checked against the saved one), recording at every
iteration k the economies S_k, the best shares B_k, and the rule fitted on them, pi_{k+1}. Then, for
several k:
  1. the split: the GRU of pi_{k+1}, run on the economies of iterations k-1 and k (no look ahead);
     whiten h, and sort its directions by how much economies at the same period differ along them
     (gpdp.memory_split.within_period_split);
  2. policy GPs fitted on (S_k, B_k) with different inputs, the GRU kept fixed:
       trained      pi_{k+1} itself (the method's own joint fit)
       zkh          (z, K, h), refitted with the standard policy-GP fit (same fitter as below)
       zkhH<n>      (z, K, h_H), h_H the n most invariant directions of h
       zkt          (z, K, T - t), with the date: the reference
       zk           (z, K), no date and no memory
  3. each judged on the NEXT iteration: economies S_{k+1} (generated by pi_{k+1}) and their best
     shares B_{k+1}: share error (overall and periods 120-126) and consumption lost over the whole
     episode by following the GP's shares instead of B_{k+1}.
The best response itself moves between iterations, so zkt's error is the part due to that alone;
the excess of the memory variants over zkt is their failure to carry over to new economies.

    python experiments/gpdp/split_diagnostic.py --seeds 0 1 2 3 4
"""

import argparse
import json
import pickle
import sys
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from memory_checks import ce_loss, share_error  # noqa: E402

from hamlab.solvers.gpdp.config import args as GPDPArgs  # noqa: E402
from hamlab.solvers.gpdp import backward as gb  # noqa: E402
from hamlab.solvers.gpdp import memory as gm  # noqa: E402
from hamlab.solvers.gpdp import memory_split as gs  # noqa: E402
from hamlab.solvers.gpdp import policy as gpol  # noqa: E402
from hamlab.solvers.gpdp import train as gt  # noqa: E402
from hamlab.solvers.gp_critic.critic import aggregate_features, gp_predict, init_hyper  # noqa: E402
from hamlab.models import make as make_model  # noqa: E402

OUT = Path(__file__).resolve().parent / "results"
ROOT = Path(__file__).resolve().parents[2]
LOGIT_BOUNDS = (float(gpol.logit(gpol.SHARE_CLIP[0])), float(gpol.logit(gpol.SHARE_CLIP[1])))


def replay(seed):
    """Replay memlearn_v4_zkh_s<seed>; return per-iteration records (stations S_k, best shares B_k,
    rule pi_{k+1} fitted on them), and the max |difference| of the final rule's weights from the saved run."""
    records = []
    original = gm.fit_memory_policy

    def recording_fit(env, stations, targets, gru, **kw):
        policy, info = original(env, stations, targets, gru, **kw)
        records.append(dict(stations=stations, targets=targets, policy=policy))
        return policy, info

    gm.fit_memory_policy = recording_fit
    try:
        a = GPDPArgs()
        a.single_vgp, a.alpha, a.policy_time, a.policy_memory_learn = True, 1.0, False, True
        a.num_iterations, a.seed, a.eval_frequency, a.save = 20, seed, 10_000, False
        gt.train(a)
    finally:
        gm.fit_memory_policy = original
    with open(ROOT / f"runs/endogenous/gpdp/memlearn_v4_zkh_s{seed}/gpdp_agent.pkl", "rb") as f:
        saved = pickle.load(f).mf_params
    diff = float(jnp.max(jnp.abs(records[-1]["policy"].gp.alpha - saved.gp.alpha)))
    return records, diff


def features(env, gru, seq, n_periods):
    """(z, K) and the memory h along station paths: (n_periods, N, 2), (n_periods, N, d)."""
    zk = np.asarray(jax.vmap(lambda a: aggregate_features(env, a))(seq))[:n_periods]
    h = np.asarray(gm.hidden_sequence(gru, gm.path_obs(seq)))[:n_periods]
    return zk, h


def fit_fixed(X, Y, steps):
    """Standard bounded policy-GP fit on fixed inputs X ((T-1), N, D) and best shares Y ((T-1), N, J)."""
    gp, _ = gb.fit_gp_bounded(
        jnp.asarray(X.reshape(-1, X.shape[-1]), jnp.float32), gpol.logit(Y).reshape(-1, Y.shape[-1]),
        init_hyper(X.shape[-1], X.shape[-1]), steps,
    )
    return gp


def predict_fixed(gp, X):
    """Shares (T-1, N, J) from a GP on fixed inputs, logits clipped to the targets' range (as the method)."""
    logits = gp_predict(gp, jnp.asarray(X.reshape(-1, X.shape[-1]), jnp.float32))
    return jax.nn.sigmoid(jnp.clip(logits, *LOGIT_BOUNDS)).reshape(*X.shape[:2], -1)


def period_error(ref, query, late_from=110):
    """
    How precisely a representation tells the period on new economies: each point of `query`
    (T, M, d) gets the period of its nearest neighbour in `ref` (T, N, d). Returns the mean absolute
    error in periods, overall and from period `late_from` on.
    """
    T = ref.shape[0]
    R, Q = ref.reshape(-1, ref.shape[-1]), query.reshape(-1, query.shape[-1])
    t_ref = np.repeat(np.arange(T), ref.shape[1])
    t_q = np.repeat(np.arange(T), query.shape[1])
    d2 = (Q**2).sum(1)[:, None] - 2 * Q @ R.T + (R**2).sum(1)[None, :]
    err = np.abs(t_ref[np.argmin(d2, axis=1)] - t_q)
    return float(err.mean()), float(err[t_q >= late_from].mean())


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    p.add_argument("--iterations", type=int, nargs="+", default=[4, 6, 8, 10, 12, 14, 16, 18])
    p.add_argument("--invariant", type=int, nargs="+", default=[1, 2, 4])
    p.add_argument("--steps", type=int, default=300)
    p.add_argument("--out", default="split_diagnostic.json")
    cli = p.parse_args()

    env = make_model("krusell_smith")
    gamma = 0.95
    out = dict(runs={}, iterations=cli.iterations, invariant=cli.invariant)
    for seed in cli.seeds:
        records, diff = replay(seed)
        print(f"seed {seed}: replayed, final rule vs saved run: max |weight difference| = {diff:.2e}", flush=True)
        rows = []
        for k in cli.iterations:
            S_prev, S, B = records[k - 1]["stations"], records[k]["stations"], records[k]["targets"]
            policy = records[k]["policy"]
            S_next, B_next = records[k + 1]["stations"], records[k + 1]["targets"]
            n_periods = B.shape[0]
            gru = policy.gru
            # --- 1. the split, from the economies of iterations k-1 and k only ---
            h_prev = features(env, gru, S_prev, n_periods)[1]
            zk, h = features(env, gru, S, n_periods)
            zk_next, h_next = features(env, gru, S_next, n_periods)
            basis = gs.within_period_split(np.concatenate([h_prev, h], axis=1))
            # --- 2. and 3. policy GPs, judged on the next iteration ---
            preds = dict(trained=np.asarray(jnp.stack([
                gpol.predict_shares_memory(env, policy, jax.tree.map(lambda x: x[t], S_next), jnp.asarray(h_next[t]))
                for t in range(n_periods)
            ])))
            fixed = dict(zkh=(np.concatenate([zk, h], -1), np.concatenate([zk_next, h_next], -1)))
            for n in cli.invariant:
                fixed[f"zkhH{n}"] = (
                    np.concatenate([zk, gs.project(basis, h, n)], -1),
                    np.concatenate([zk_next, gs.project(basis, h_next, n)], -1),
                )
            for name, (X, X_next) in fixed.items():
                preds[name] = np.asarray(predict_fixed(fit_fixed(X, B, cli.steps), X_next))
            for name, use_time in (("zkt", True), ("zk", False)):
                X, Y = gpol.training_data(env, S, B, use_time=use_time)
                gp = gpol.fit_policy_gp(X, Y, cli.steps)[0]
                preds[name] = np.asarray(gpol.path_shares(env, gp, jax.tree.map(lambda x: x[:n_periods], S_next)))
            row = dict(iteration=k, within_share=basis.within_share.round(4).tolist(), variants={}, period_error={})
            # --- how precisely each representation tells the period on the next iteration's economies ---
            ref = np.concatenate([h_prev, h], axis=1)
            for n in [*cli.invariant, h.shape[-1]]:
                e_all, e_late = period_error(gs.project(basis, ref, n), gs.project(basis, h_next, n))
                row["period_error"][f"h_{n}_most_invariant" if n < h.shape[-1] else "h_all"] = dict(all=e_all, from_110=e_late)
            for name, pred in preds.items():
                err, blocks = share_error(S_next, pred, B_next)
                _, ce_all = ce_loss(env, S_next, jnp.asarray(pred), B_next, gamma)
                row["variants"][name] = dict(share_error=err, share_error_120_126=blocks["120-126"], ce_loss_all_pct=ce_all)
            rows.append(row)
            print(f"  k={k:2d} within-share {np.round(basis.within_share, 2)} | CE loss next iteration: "
                  + " ".join(f"{n} {v['ce_loss_all_pct']:.3f}%" for n, v in row["variants"].items()), flush=True)
        out["runs"][f"memlearn_v4_zkh_s{seed}"] = dict(replay_max_weight_diff=diff, rows=rows)
        OUT.mkdir(exist_ok=True)
        (OUT / cli.out).write_text(json.dumps(out, indent=2))

    # --- summary: medians over seeds and iterations ---
    allrows = [r for run in out["runs"].values() for r in run["rows"]]
    names = list(allrows[0]["variants"])
    out["summary_median"] = {
        n: {m: float(np.median([r["variants"][n][m] for r in allrows])) for m in ("share_error", "share_error_120_126", "ce_loss_all_pct")}
        for n in names
    }
    out["summary_within_share_median"] = np.median([r["within_share"] for r in allrows], axis=0).round(4).tolist()
    out["summary_period_error_median"] = {
        n: {m: float(np.median([r["period_error"][n][m] for r in allrows])) for m in ("all", "from_110")}
        for n in allrows[0]["period_error"]
    }
    print(json.dumps(out["summary_median"], indent=1))
    print("median period error on the next iteration's economies (periods):", json.dumps(out["summary_period_error_median"]))
    print("median within-period share per direction (most to least invariant):", out["summary_within_share_median"])
    (OUT / cli.out).write_text(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
